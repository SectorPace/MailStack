export type MailKey = keyof typeof MAIL_DICT;

/** 取当前语言的文案；缺失键由类型系统挡住（不会走到运行时兜底）。 */
export function mt(lang: Lang, key: MailKey, params?: Record<string, string | number>): string {
  let s: string = MAIL_DICT[key][lang === "zh" ? 0 : 1];
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** 语言标签（用于 `<html lang>` / 格式化日期）。 */
export function htmlLang(lang: Lang): string {
  return lang === "zh" ? "zh-CN" : "en";
}
